#!/usr/bin/env python3
"""Generate src/styles/themes.css from Omarchy's theme colours.

Omarchy (MIT, https://github.com/basecamp/omarchy) ships each theme's palette
as themes/<name>/colors.toml. This maps a palette onto the site's tokens.
Run it when Omarchy's themes change: scripts/gen-themes.py [OMARCHY_THEMES_DIR]
"""
import sys, tomllib, pathlib

THEMES = ["tokyo-night", "catppuccin", "gruvbox", "everforest", "kanagawa", "nord",
          "rose-pine", "osaka-jade", "ristretto", "matte-black", "catppuccin-latte", "flexoki-light"]
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/omarchy/themes")

def rgb(h): h = h.lstrip("#"); return [int(h[i:i+2], 16) for i in (0, 2, 4)]
def hexc(c): return "#" + "".join(f"{round(max(0, min(255, v))):02x}" for v in c)
def mix(a, b, t): return hexc([x * (1 - t) + y * t for x, y in zip(rgb(a), rgb(b))])
def lum(h):
    c = [v / 255 for v in rgb(h)]
    c = [v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4 for v in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def contrast(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True); return (la + 0.05) / (lb + 0.05)
def readable(fg, bg, toward, need=4.5):
    """Move fg toward `toward` until it reaches the contrast it needs on bg."""
    t = 0.0
    while contrast(fg2 := mix(fg, toward, t), bg) < need and t < 1: t += 0.05
    return fg2

out = ["/* Generated by scripts/gen-themes.py from Omarchy's theme palettes (MIT). Don't edit. */"]
for i, name in enumerate(THEMES):
    c = tomllib.loads((src / name / "colors.toml").read_text())
    light = c.get("mode") == "light"
    bg = c["background"].lower()
    ink = "#000000" if light else "#ffffff"
    fg = c.get("bright_foreground", c["foreground"]) if not light else c["foreground"]
    surface = mix(bg, ink, 0.035 if light else 0.04)
    tok = {
        "bg": bg,
        "bg-deep": mix(bg, "#000000", 0.04 if light else 0.25),
        "surface": surface,
        "surface-2": mix(bg, ink, 0.07),
        "border": mix(bg, ink, 0.12),
        "border-strong": mix(bg, ink, 0.24),
        "text": readable(fg, bg, ink, 7),
        "text-2": readable(c["foreground"], bg, ink, 5.5),
        "muted": readable(mix(c["foreground"], bg, 0.35), bg, ink, 4.6),
        "accent": readable(c["accent"], bg, ink, 4.5),
        "accent-ink": "#ffffff" if lum(c["accent"]) < 0.3 else "#0c0e10",
        "works": readable(c["green"], surface, ink, 4.5),
        "partial": readable(c["yellow"], surface, ink, 4.5),
        "wip": readable(c.get("magenta", c["accent"]), surface, ink, 4.5),
        "selection": c.get("selection", mix(bg, c["accent"], 0.3)),
    }
    sel = (":root, " if i == 0 else "") + f'[data-theme="{name}"]'
    body = "".join(f"--{k}:{v};" for k, v in tok.items())
    out.append(f"{sel}{{{body}color-scheme:{'light' if light else 'dark'};}}")
pathlib.Path(__file__).resolve().parent.parent.joinpath("src/styles/themes.css").write_text("\n".join(out))
pathlib.Path(__file__).resolve().parent.parent.joinpath("src/lib/themes.json").write_text(
    __import__("json").dumps(THEMES))
print(f"{len(THEMES)} themes")
